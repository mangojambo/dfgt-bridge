CATALOGS = {'en': EN, 'pt-BR': PT_BR}


def translate(key, locale=DEFAULT_LOCALE, *, catalogs=CATALOGS, **params):
    english = catalogs.get(DEFAULT_LOCALE, EN)
    template = catalogs.get(locale, {}).get(key, english.get(key, key))
    try:
        return template.format(**params)
    except (KeyError, ValueError):
        return template


def missing_translations(catalogs=CATALOGS):
    keys = set(catalogs[DEFAULT_LOCALE])
    return {locale: sorted(keys-set(catalogs.get(locale, {}))) for locale in LOCALES if locale != DEFAULT_LOCALE}


def localized_error(detail, locale=DEFAULT_LOCALE):
    checks = (
        ('ffb_strength: inteiro 0..100', 'error.invalid_strength'),
        ('ffb_max_strength: inteiro 0..100', 'error.invalid_maximum'),
        ('Polaridade deve ser -1 ou 1', 'error.invalid_polarity'),
        ('Slew deve ser finito e positivo', 'error.invalid_slew'),
        ('Duração:', 'error.invalid_duration'),
        ('Identidade, entrada ou preset inválidos', 'error.invalid_profile'),
        ('Mapeamento precisa de', 'error.invalid_mapping'),
        ('Lista de entradas inválida', 'error.invalid_mapping'),
        ('Eixos incompletos', 'error.invalid_mapping'),
        ('Já existe um perfil com esse nome', 'error.profile_exists'),
    )
    key = next((key for pattern, key in checks if detail.startswith(pattern)), None)
    return translate(key, locale) if key else detail


def target_key(target):
    return 'target.'+target.replace(':', '.')


def source_label(source, locale=DEFAULT_LOCALE):
    if source.startswith('key:'):
        code = source[4:]
        return f'{code} · {translate("source."+code, locale)}'
    key = target_key(source)
    return 'ABS_HAT0 · '+translate(key, locale)
